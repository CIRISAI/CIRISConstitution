#!/usr/bin/env python3
"""The registry's families fit their kind profiles: generate the Lean data and check it in Python too.

Reads formal/derivation/family_kind_verb.tsv, writes the DATA section of
formal/family_model/FamilyModel.lean between the markers, and checks every family against the
kind profile and the carries firewall the Lean file defines. Exit 1 on any misfit or drift.
"""
import csv, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "formal/derivation/family_kind_verb.tsv")
LEAN = os.path.join(ROOT, "formal/family_model/FamilyModel.lean")
KIND = {"Priorities": "priorities", "Rules": "rules", "Manner": "manner", "Identity": "identity", "Confidence": "confidence",
        "Facts": "facts", "Circumstances": "circumstances", "Process": "process", "Model": "model", "Structure": "structure", "Premises": "premises"}
SIDE = {"THING": "thing", "ACCOUNT": "account"}
VERB = {"attest": "attest", "authorize": "authorize", "replace": "replace", "withdraw": "withdraw", "recant": "recant", "carries": "carries"}
# the profile: the verbs each kind admits (the registry's occupancy plus the grid's named gaps; the principled empties are refused)
PROFILE = {
    "priorities": {"attest", "withdraw", "recant", "carries"},
    "rules": {"attest", "authorize", "replace", "withdraw", "recant", "carries"},
    "manner": {"attest", "replace", "withdraw", "recant", "carries"},
    "identity": {"attest", "authorize", "replace", "withdraw"},
    "confidence": {"attest", "replace", "withdraw", "recant", "carries"},
    "facts": {"attest", "replace", "withdraw", "recant", "carries"},
    "circumstances": {"attest", "replace", "withdraw", "carries"},
    "process": {"attest", "authorize", "replace", "withdraw", "carries"},
    "model": {"attest", "replace", "withdraw", "recant", "carries"},
    "structure": {"attest", "replace", "withdraw", "recant", "carries"},
    "premises": {"attest", "replace", "withdraw", "recant", "carries"},
}
THING = {"rules", "identity", "circumstances", "process", "structure"}
def main():
    rows = list(csv.DictReader(open(TSV, encoding="utf-8"), delimiter="\t"))
    errs, lean = [], []
    for r in rows:
        k = KIND.get(r["kind"]); s = SIDE.get(r["side"])
        if not k or not s: errs.append(f"{r['family']}: unknown kind/side {r['kind']}/{r['side']}"); continue
        verbs = [VERB[v.strip()] for v in r["verbs"].split(",") if v.strip()]
        for v in verbs:
            if v not in PROFILE[k]: errs.append(f"{r['family']}: verb {v} outside the {k} profile")
        if (k in THING) != (s == "thing"): errs.append(f"{r['family']}: side {s} is not the side of kind {k}")
        rf = r.get("reference", "—")
        mode, ck = (rf.split(":", 1) + [""])[:2] if rf != "—" else ("", "")
        if rf != "—" and mode not in ("pre", "carry"): errs.append(f"{r['family']}: reference mode {mode} unknown")
        if mode == "carry" and "carries" not in verbs: errs.append(f"{r['family']}: carries a kind without the verb")
        if mode == "carry" and KIND.get(ck) == "identity": errs.append(f"{r['family']}: carries Identity, the firewalled cell")
        if "carries" in verbs and mode != "carry": errs.append(f"{r['family']}: the verb carries names no carried kind")
        if ck and ck != "any" and ck not in KIND: errs.append(f"{r['family']}: reference kind {ck} unknown")
        mr = r.get("maintains_record", "no") == "yes"
        if rf == "—": ref = "none"
        elif ck == "any": ref = "some ⟨.pre, none⟩"
        else: ref = f"some ⟨.{mode}, some .{KIND[ck]}⟩"
        name = r["family"].replace("\\", "\\\\").replace('"', '\\"')
        lean.append(f'  ⟨"{name}", ⟨.{k}, [{", ".join("."+v for v in verbs)}], {ref}⟩, ⟨{"true" if mr else "false"}, '
                    f'{".legalHold" if mr else ".dsar"}, {".byteEqual" if mr else ".none"}⟩⟩')
    src = open(LEAN, encoding="utf-8").read()
    m = re.search(r"(-- DATA BEGIN \(generated by tools/check_family_kinds.py from formal/derivation/family_kind_verb.tsv\)\n)(.*?)(\n-- DATA END)", src, re.S)
    if not m: errs.append("FamilyModel.lean has no DATA markers")
    else:
        defs = []
        for i, row in enumerate(lean):
            defs.append(f"def f{i} : FamilyRow :=\n{row}\ntheorem fit{i} : fits f{i} = true := by decide")
        body = "\n".join(defs) + "\n\ndef families : List FamilyRow := [" + ", ".join(f"f{i}" for i in range(len(lean))) + "]"
        if m.group(2) != body:
            if "--check" in sys.argv: errs.append("FamilyModel.lean DATA section is stale (run tools/check_family_kinds.py)")
            else:
                open(LEAN, "w", encoding="utf-8").write(src[:m.start(2)] + body + src[m.end(2):])
    print(f"family kinds: {len(rows)} families, {sum(1 for r in rows if r.get('maintains_record')=='yes')} maintain the record, "
          f"{sum(1 for r in rows if 'carries' in r['verbs'])} carry; {len(errs)} misfit(s)")
    for e in errs: print("  ERR", e)
    return 1 if errs else 0
if __name__ == "__main__":
    sys.exit(main())
